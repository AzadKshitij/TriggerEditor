class Source(TriggerNode):
    node_title = "Source"

    def __init__(self, scene, frame) -> None:
        self._frame = frame
        super().__init__(scene, inputs=[], outputs=[3])
        self.value = [{"data": frame, "variable_name": "var_src"}]
        self.markDirty(False)
        self.markInvalid(False)

    def evalImplementation(self):
        self.value = [{"data": self._frame, "variable_name": "var_src"}]
        self.markDirty(False)
        self.markInvalid(False)
        return self.value


def frame(rows: int = 1000) -> pl.LazyFrame:
    return pl.DataFrame(
        {
            "n": list(range(rows)),
            "t": [f"{i % 7}" for i in range(rows)],
        }
    ).lazy()


def build(qtbot, data=None, wired: bool = True):
    window = TriggerSubWindow()
    qtbot.addWidget(window)
    cls = get_class_from_opcode(ReportNodes.DATA_PROFILE, NodeTypes.REPORT)
    node = cls(window.scene)
    source = None
    if wired:
        source = Source(window.scene, frame() if data is None else data)
        Edge(window.scene, source.outputs[0], node.inputs[0])
    node.markDirty(True)
    node.eval()
    return window, source, node


def test_node_identity_and_sockets(qtbot):
    _window, _source, node = build(qtbot, wired=False)
    assert node.node_title == "Data Profile"
