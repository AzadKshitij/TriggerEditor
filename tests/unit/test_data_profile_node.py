def test_epoch_bumps_only_for_a_new_input_frame(qtbot):
    _window, source, node = build(qtbot)
    content = node.content
    epoch = content._epoch
    node.markDirty(True)
    node.eval()
    assert content._epoch == epoch  # same frame object
    content.set_setting("top_n", 9, "Profile Top values Changed")
    assert content._epoch == epoch
    assert content.key()[1] != core_key(core.DEFAULTS)
    source._frame = frame(10)
    source.markDirty(True)
    node.markDirty(True)
    node.eval()
    assert content._epoch == epoch + 1


