def test_serialize_round_trip_and_old_file_defaults(qtbot):
    _window, _source, node = build(qtbot, wired=False)
    content = node.content
    assert content.settings == core.DEFAULTS
    state = content.serialize()
    state["settings"]["top_n"] = 12
    content.deserialize(state, {})
    assert content.settings["top_n"] == 12
    # an old file has no settings key at all
    state.pop("settings")
    content.deserialize(state, {})
    assert content.settings == core.DEFAULTS


def test_out_of_range_settings_are_clamped_on_load(qtbot):
    _window, _source, node = build(qtbot, wired=False)
