def run_frame(rows: int = 1000, **settings) -> pl.DataFrame:
    """What the generated code leaves in ``var_profile_<id>`` after a Run."""
    return core.run_node([frame(rows)], settings)[1].collect()


def test_on_run_result_hands_the_run_profile_over(qtbot):
    _window, _source, node = build(qtbot, frame(1000))
    content = node.content
    assert content.run_profile() is None  # nothing has run yet
    content.on_run_result({content.output_variables[1]: run_frame(1000).lazy()})
    run = content.run_profile()
    assert run is not None
    assert run.row_count == 1000  # the whole input, not the 100-row preview
    assert [c.name for c in run.columns] == ["n", "t"]
    assert run.columns[0].histogram  # the chart data came through the table


