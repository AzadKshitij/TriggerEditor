def test_the_run_hook_is_called_on_the_gui_thread_by_the_window(qtbot):
    """The window hands a finished node's variables to ``on_run_result``."""
    import threading

    _window, _source, node = build(qtbot, frame(300))
    content = node.content
    seen = []
    real = content.on_run_result

    def spy(variables):
        seen.append(threading.current_thread() is threading.main_thread())
        real(variables)

    content.on_run_result = spy

    result = SimpleNamespace(
        success=True,
        variables={content.output_variables[1]: run_frame(300).lazy()},
    )
    _window._on_node_finished(node, result)
    assert seen == [True]
    assert content.run_profile().row_count == 300


