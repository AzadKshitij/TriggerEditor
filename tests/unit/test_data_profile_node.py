def test_profile_socket_is_lazy_with_exact_schema(qtbot, monkeypatch):
    import trigger_designer.qt.widgets.nodes.Report.data_profile as mod

    calls = []
    real = mod.profile_frame

    def counting(*args, **kwargs):
        calls.append(1)
        return real(*args, **kwargs)

    monkeypatch.setattr(mod, "profile_frame", counting)
    _window, _source, node = build(qtbot)
    socket = node.value[1]["data"]
    assert isinstance(socket, pl.LazyFrame)
    assert socket.collect_schema() == pl.Schema(PROFILE_SCHEMA)
    assert node.content._cache is None
    assert calls == []
    first = socket.collect()
    second = socket.collect()
    assert first.equals(second)
    assert len(calls) == 1
    assert node.content.current_profile() is not None


